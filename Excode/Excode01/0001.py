import pandas as pd

# สร้างข้อมูลจำลอง
data = {
    'ชื่อ': ['นัท', 'บีม', 'ฟ้า', 'เจ', 'มิกซ์'],
    'คะแนนสอบ': [85, 67, 90, 78, 88],
    'อายุ': [20, 21, 19, 22, 20]
}

df = pd.DataFrame(data)

# วิเคราะห์ข้อมูลเบื้องต้น
print("📊 ข้อมูลทั้งหมด:")
print(df)

print("\n📈 ค่าเฉลี่ยคะแนนสอบ:", df['คะแนนสอบ'].mean())
print("🎯 คนที่ได้คะแนนสูงที่สุด:")
print(df[df['คะแนนสอบ'] == df['คะแนนสอบ'].max()])

print("\n🧮 สถิติพื้นฐาน:")
print(df.describe())